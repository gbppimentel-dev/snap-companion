"""Validate and package independently phrased star-photo reference methods."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def prepare():
    source = json.loads((ROOT/'tools/data/photo-walkthroughs.json').read_text())
    text = (ROOT/'app/src/main/assets/ui/content.js').read_text()
    content = json.loads(text[text.index('{'):].rstrip(';\n'))
    species = {p['id']: p for p in content['species']}
    courses = {c['id']: c for c in content['courses']}
    result, seen = {}, set()
    for row in source['methods']:
        p, c = species[row['species']], courses[row['course']]
        identity = (p['id'], row['stars'], c['id'], row['title'])
        assert identity not in seen and row['stars'] in (1, 2, 3, 4), identity
        assert any(l['course'] == c['id'] for l in p['locations']), identity
        assert row['exampleLevel'] in c['levels'] or row['exampleLevel'] == 0, identity
        assert 2 <= len(row['steps']) <= 8 and row['sources'], identity
        assert all(isinstance(step, str) and step.strip() for step in row['steps'])
        assert set(row['tools']) <= {'fluffruit', 'illumina-orb', 'melody', 'scan', 'turbo'}
        assert row['shot'].strip() and row['where'].strip() and row['title'].strip()
        seen.add(identity)
        result.setdefault(f"{p['id']}:{row['stars']}", []).append({
            k: row[k] for k in ('species', 'stars', 'course', 'exampleLevel',
                               'title', 'where', 'tools', 'steps', 'shot')})
    return ('// Generated by tools/prepare_photo_walkthroughs.py; reference methods only.\n'
            'window.SnapPhotoDetails=Object.freeze('
            + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ');\n')


if __name__ == '__main__':
    (ROOT/'app/src/main/assets/ui/photo-details.js').write_text(prepare())
