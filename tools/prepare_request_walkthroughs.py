"""Package reviewed route/setup notes without exposing source links in the UI."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def prepare():
    source = json.loads((ROOT / 'tools/data/request-walkthroughs.json').read_text())
    text = (ROOT / 'app/src/main/assets/ui/content.js').read_text()
    content = json.loads(text[text.index('{'):].rstrip(';\n'))
    requests = {r['id']: r for r in content['requests']}
    result = {}
    for row in source['requests']:
        request = requests[row['id']]
        assert row['id'] not in result and row['course'] == request['course']
        assert 2 <= len(row['steps']) <= 8 and row['sources']
        assert all(isinstance(s, str) and s.strip() for s in row['steps'])
        result[row['id']] = {k: row[k] for k in ('course', 'where', 'shot', 'steps')}
    return ('// Generated by tools/prepare_request_walkthroughs.py; factual notes only.\n'
            'window.SnapRequestDetails=Object.freeze('
            + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ');\n')


if __name__ == '__main__':
    (ROOT / 'app/src/main/assets/ui/request-details.js').write_text(prepare())
