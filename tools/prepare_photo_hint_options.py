"""Restore source list boundaries in existing hints; adds no new photo advice."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT/'tools/data/photo-hint-options.json'

def clean(s):
    return re.sub(r'\s+', ' ', s.replace('PokÃ©', 'Poké')).strip()

def procedure(s):
    s = clean(s)
    replacements = [(r'Get a (?:good )?picture of','Photograph'),(r'Get a shot of','Photograph'),(r'Take a (?:good )?(?:picture|photo) of','Photograph'),(r'Get (.+?) to ',r'Prompt \1 to '),(r'This is done by','Setup:'),(r'It can be activated by','Trigger:'),(r'at the end of the stage','near the course exit'),(r'at the start of the stage','near the course entrance'),(r'in the middle area','mid-course'),(r'can be found','appears'),(r'you will need to','you need to'),(r'you have to','you need to'),(r'by throwing','using'),(r'then take a picture','then photograph'),(r'for a (?:good )?(?:picture|photo)','and photograph the response'),(r'top quality images','a clearer view'),(r'Level ([1-3])',r'research Lv. \1')]
    for pattern, value in replacements:
        s = re.sub(pattern, value, s, flags=re.I)
    return s.replace('Fluffruit','fluffruit').replace('Illumina Orbs','Illumina orbs').replace('Illumina Orb','Illumina orb')

def extract(cache):
    from bs4 import BeautifulSoup
    guide = json.loads((ROOT/'app/src/main/assets/guidebook.json').read_text())
    rows = []
    for cue in guide['photoCues']:
        name = cue['source'].split('/')[-1]
        path = cache/('photodex__'+name)
        if not path.is_file():
            continue
        soup = BeautifulSoup(path.read_bytes(), 'html.parser')
        for table in soup.select('table.dextab'):
            trs = table.find_all('tr', recursive=False)
            if not trs or clean(trs[0].get_text(' ', strip=True)) != 'Star Rated Photos':
                continue
            for tr in trs[1:]:
                cells = tr.find_all('td', recursive=False)
                if not cells or not re.match(fr'{cue["stars"]} Star', cells[0].get_text(' ', strip=True)):
                    continue
                cell = cells[-1]
                # Line breaks separate the source's alternate photo opportunities.
                for br in cell.find_all('br'):
                    br.replace_with('␞')
                parts = [procedure(s) for s in cell.get_text(' ', strip=True).split('␞') if clean(s)]
                # Vivillon's first two independent photos share a source paragraph.
                if cue['species'] == 666 and cue['stars'] == 3 and parts:
                    parts = parts[0].split('. Photograph ', 1) + parts[1:]
                    if len(parts) == 3:
                        parts[0] += '.'
                        parts[1] = 'Photograph '+parts[1]
                if len(parts) > 1 and clean(' '.join(parts)) == clean(cue['procedure']):
                    rows.append({'species':cue['species'],'stars':cue['stars'],'options':parts,'source':cue['source']})
    DATA.write_text(json.dumps({'schema':1,'boundary':'Original reference line breaks; wording already present in guidebook','hints':rows},ensure_ascii=False,indent=2)+'\n')

def prepare():
    guide = json.loads((ROOT/'app/src/main/assets/guidebook.json').read_text())
    cues = {(r['species'],r['stars']):r['procedure'] for r in guide['photoCues']}
    out = {}
    for row in json.loads(DATA.read_text())['hints']:
        identity = (row['species'],row['stars'])
        parts = row['options']
        assert len(parts)>1 and all(isinstance(p,str) and p.strip() for p in parts), identity
        assert clean(' '.join(parts)) == clean(cues[identity]), identity
        key = f'{identity[0]}:{identity[1]}'
        assert key not in out, identity
        out[key] = parts
    return '// Generated by tools/prepare_photo_hint_options.py; original hint boundaries only.\nwindow.SnapPhotoOptions=Object.freeze('+json.dumps(out,ensure_ascii=False,separators=(',',':'))+');\n'

if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--reference-cache',type=Path)
    args=parser.parse_args()
    if args.reference_cache:
        extract(args.reference_cache)
    (ROOT/'app/src/main/assets/ui/photo-options.js').write_text(prepare())
